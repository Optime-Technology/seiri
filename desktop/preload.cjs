'use strict';
/** Arayüze yalnızca sınırlı masaüstü işlemlerini açar. */
const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('ZamanDesktop',Object.freeze({
 workspaceKind:process.argv.includes('--seiri-account-space')?'account':'device',
 spaceInfo:()=>ipcRenderer.invoke('space:info'),
 spaceAccount:()=>ipcRenderer.invoke('space:account'),spaceDevice:()=>ipcRenderer.invoke('space:device'),
 prepareTransfer:text=>ipcRenderer.invoke('space:prepare-transfer',text),transferInfo:()=>ipcRenderer.invoke('space:transfer-info'),transferRead:()=>ipcRenderer.invoke('space:transfer-read'),transferCancel:hash=>ipcRenderer.invoke('space:transfer-cancel',hash),transferDone:hash=>ipcRenderer.invoke('space:transfer-done',hash),
 syncWatch:()=>ipcRenderer.invoke('cloud-sync:watch'),onSyncWake:fn=>{const listener=()=>fn();ipcRenderer.on('cloud-sync-wake',listener);return()=>ipcRenderer.removeListener('cloud-sync-wake',listener);},
 syncCapture:value=>ipcRenderer.invoke('cloud-sync:capture',value),syncRun:()=>ipcRenderer.invoke('cloud-sync:run'),syncFileInfo:()=>ipcRenderer.invoke('cloud-sync:file-info'),syncFileUpload:(meta,bytes)=>ipcRenderer.invoke('cloud-sync:file-upload',meta,bytes),syncFileDownload:(id,assetId)=>ipcRenderer.invoke('cloud-sync:file-download',id,assetId),
 cloudAuthInfo:()=>ipcRenderer.invoke('cloud-auth:info'),
 cloudAuthRefresh:()=>ipcRenderer.invoke('cloud-auth:refresh'),
 cloudAuthSignIn:()=>ipcRenderer.invoke('cloud-auth:signin'),
 cloudAuthCancel:()=>ipcRenderer.invoke('cloud-auth:cancel'),
 cloudAuthSignOut:()=>ipcRenderer.invoke('cloud-auth:signout'),
 onCloudAuthChanged:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('cloud-auth-changed',listener);return()=>ipcRenderer.removeListener('cloud-auth-changed',listener);},
 vaultInfo:()=>ipcRenderer.invoke('vault:info'),
 vaultSetup:(pin,ack)=>ipcRenderer.invoke('vault:setup',pin,ack),
 vaultUnlock:(pin,scope)=>ipcRenderer.invoke('vault:unlock',pin,scope),
 vaultHello:scope=>ipcRenderer.invoke('vault:hello',scope),
 vaultSeal:(token,id,details,meta)=>ipcRenderer.invoke('vault:seal',token,id,details,meta),
 vaultOpen:(token,id,box)=>ipcRenderer.invoke('vault:open',token,id,box),
 vaultForget:(token,id)=>ipcRenderer.invoke('vault:forget',token,id),
 vaultLock:()=>ipcRenderer.invoke('vault:lock'),
 vaultChangePin:(token,oldPin,newPin)=>ipcRenderer.invoke('vault:change-pin',token,oldPin,newPin),
 vaultExportKeys:(token,password)=>ipcRenderer.invoke('vault:export-keys',token,password),
 vaultImportKeys:(token,password,bundle)=>ipcRenderer.invoke('vault:import-keys',token,password,bundle),
 onVaultLocked:callback=>ipcRenderer.on('vault-locked',()=>callback()),
 backupList:()=>ipcRenderer.invoke('backup:list'),
 backupCreate:text=>ipcRenderer.invoke('backup:create',text),
 backupRead:id=>ipcRenderer.invoke('backup:read',id),
 checkUpdates:()=>ipcRenderer.invoke('updates:check'),
 getInfo:()=>ipcRenderer.invoke('desktop:info'),
 schedule:items=>ipcRenderer.invoke('desktop:schedule',items),
 test:()=>ipcRenderer.invoke('desktop:test'),
 setLogin:enabled=>ipcRenderer.invoke('desktop:login',enabled),
 openExternal:url=>ipcRenderer.invoke('desktop:external',url),
 openPDF:bytes=>ipcRenderer.invoke('desktop:pdf',bytes),
 onOpenEntry:callback=>ipcRenderer.on('open-entry',(_event,id)=>callback(id)),
 onDownload:callback=>ipcRenderer.on('download-result',(_event,status)=>callback(status))
}));
